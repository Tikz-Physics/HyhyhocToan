export function getPetStage(completedCount) {
  for (let i = PET_STAGES.length - 1; i >= 0; i--) {
    if (completedCount >= PET_STAGES[i].minTasks) {
      return PET_STAGES[i];
    }
  }
  return PET_STAGES[0];
}
