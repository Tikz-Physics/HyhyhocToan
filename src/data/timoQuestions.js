// Trình tạo đề thi ngẫu nhiên (Lấy 5 câu từ mỗi chuyên đề để tạo đề 25 câu cân đối)
export function generateRandomTimoExam() {
  const allExams = [TIMO_EXAM_SET_1, TIMO_EXAM_SET_2, TIMO_EXAM_SET_3, TIMO_EXAM_SET_4];
  const allQuestions = allExams.flat();

  const sections = ['logic', 'arithmetic', 'number_theory', 'geometry', 'combinatorics'];
  const pickedQuestions = [];

  sections.forEach((sec) => {
    const secQuestions = allQuestions.filter((q) => q.section === sec);
    // Shuffle
    const shuffled = [...secQuestions].sort(() => Math.random() - 0.5);
    // Pick 5
    pickedQuestions.push(...shuffled.slice(0, 5));
  });

  // Re-index questions 1 to 25
  return pickedQuestions.map((q, idx) => ({
    ...q,
    id: `rand_${idx + 1}`,
  }));
}

